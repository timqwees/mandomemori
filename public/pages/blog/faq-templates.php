// Map article categories/tags to FAQ groups
$categoryFaqMap = [
    'чистка и уход' => ['cleaning', 'care', 'diy'],
    'уход за материалами' => ['care', 'materials'],
    'реставрация' => ['restoration', 'price'],
    'ремонт' => ['restoration', 'price'],
    'тренды' => ['sneakers', 'general'],
    'советы' => ['cleaning', 'care', 'seasonal', 'diy'],
];

// Build FAQ for specific article
function buildArticleFaq(array $article, array $faqTemplates, array $categoryFaqMap): array {
    $faq = [];
    $usedQuestions = [];
    
    // 1. Category-based FAQs
    $cat = $article['category'] ?? '';
    $groups = $categoryFaqMap[$cat] ?? ['general'];
    foreach ($groups as $group) {
        if (!empty($faqTemplates[$group])) {
            foreach ($faqTemplates[$group] as $item) {
                $q = $item['question'];
                if (!in_array($q, $usedQuestions)) {
                    $faq[] = $item;
                    $usedQuestions[] = $q;
                    if (count($faq) >= 8) break 2;
                }
            }
        }
    }
    
    // 2. Tag-based specific FAQs
    $tags = array_map('trim', explode(',', $article['tags'] ?? ''));
    $tagKeywords = [
        'белые' => 'sneakers',
        'замш' => 'care',
        'нубук' => 'care',
        'кожа' => 'care',
        'мембрана' => 'care',
        'подошва' => 'cleaning',
        'пятна' => 'cleaning',
        'запах' => 'care',
        'реставрация' => 'restoration',
        'покраска' => 'restoration',
        'подготовка' => 'seasonal',
        'реагенты' => 'seasonal',
    ];
    foreach ($tags as $tag) {
        foreach ($tagKeywords as $kw => $group) {
            if (mb_stripos($tag, $kw) !== false && !empty($faqTemplates[$group])) {
                foreach ($faqTemplates[$group] as $item) {
                    $q = $item['question'];
                    if (!in_array($q, $usedQuestions) && count($faq) < 8) {
                        $faq[] = $item;
                        $usedQuestions[] = $q;
                    }
                }
            }
        }
    }
    
    // 3. Fallback to general
    if (count($faq) < 4 && !empty($faqTemplates['general'])) {
        foreach ($faqTemplates['general'] as $item) {
            $q = $item['question'];
            if (!in_array($q, $usedQuestions) && count($faq) < 8) {
                $faq[] = $item;
                $usedQuestions[] = $q;
            }
        }
    }
    
    return array_slice($faq, 0, 8);
}